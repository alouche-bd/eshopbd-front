/**
 * ISO 3166-1 alpha-2 country codes where French is an official, majority,
 * or co-official language — these all default the UI to French.
 *
 * Source: OIF / official language declarations. Canada is intentionally
 * EXCLUDED because outside Quebec the default is English; explicit override
 * to "fr" can be added later if needed.
 *
 * Used by localeForUser() below.
 */
export const FRENCH_SPEAKING_COUNTRIES = new Set([
    // Europe
    "FR", "BE", "LU", "MC", "CH", "AD",
    // North + West Africa
    "DZ", "MA", "TN", "MR",
    "SN", "ML", "BF", "NE", "CI", "TG", "BJ", "GN",
    // Central Africa
    "CM", "GA", "CG", "CD", "CF", "TD", "GQ",
    // East Africa / Indian Ocean
    "DJ", "KM", "MG", "RW", "BI", "SC",
    // Caribbean / Atlantic
    "HT",
    // French overseas territories / collectivities
    "GP", "MQ", "GF", "RE", "YT", "BL", "MF", "PM",
    // Pacific
    "NC", "PF", "WF",
    // Levant (co-official / large francophone diaspora)
    "LB",
    // Other
    "VU",
]);

/**
 * Returns the locale code to use for a given user (spec §16).
 *   - billing_country_code in FRENCH_SPEAKING_COUNTRIES  → "fr"
 *   - billing_country_code missing/empty                 → "fr" (fallback)
 *   - any other country code                             → "en"
 */
export const localeForUser = (user) => {
    const country = (user && user.billing_country_code) || "";
    if (!country) return "fr";
    return FRENCH_SPEAKING_COUNTRIES.has(country.toUpperCase()) ? "fr" : "en";
};
